"""
src/chat_intent.py — Smart Intent Classifier for PPLE Agent Chat

Classifies each user query into one of four intent types so the
pipeline can conditionally fetch equipment data and run multi-agent
diagnosis only when actually needed.

Intent types
------------
EQUIPMENT_STATUS  — query about a specific asset's current or historical
                    condition; needs equipment data + multi-agent run.
CONCEPTUAL_TECH   — conceptual / standards / theory question within the
                    PDM/PLTU domain; needs knowledge-base only, no raw data.
GENERAL_CHAT      — greetings, identity, small-talk; needs no data at all.
OUT_OF_SCOPE      — completely outside PDM/PLTU/CBM domain; return early
                    with a polite redirect.

Design notes
------------
* NEVER import chatbot.py or replicate its branching logic.  Read only
  the *outputs* it has already computed: matched_equipment + rule_answer.
* Rule-based answer is always produced upstream and always forwarded to
  the LLM as rule_answer regardless of intent — this module only controls
  what *additional* data is fetched, not what rule-based logic runs.
* OUT_OF_SCOPE threshold is intentionally conservative: domain-adjacent
  topics (heat rate, generator theory, coal quality) are NOT out-of-scope.
"""

